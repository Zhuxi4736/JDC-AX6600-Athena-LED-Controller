# 重新设计雅典娜 LED 虚拟宠物表情 (27x5 单色点阵)
# 格式: 每帧 27 字节, 字节 x = 第 x 列, bit y(bit0=顶部)=该列第 y 行亮 (1=亮)
# 用法: python3 gen_pets.py            -> 生成所有 pet_*.bin 到 ./anim_out/
#       python3 gen_pets.py love        -> 只生成 pet_love.bin
import os

W, H = 27, 5

def frame(grid):
    """grid: 长度27的列表, 每元素是长度5的字符串('#'/'#'=亮, 其他=灭), 列优先."""
    assert len(grid) == W, "must be 27 cols"
    out = bytearray()
    for col in grid:
        assert len(col) == H, "each col must be 5 rows"
        b = 0
        for y in range(H):
            if col[y] in ('1','#'):
                b |= (1 << y)
        out.append(b)
    return bytes(out)

def bin_from_frames(frames, path):
    with open(path, 'wb') as f:
        for fr in frames:
            f.write(frame(fr))
    print(f"  wrote {path} ({len(frames)} frames)")

# 工具: 用 5x27 的字符画 (行优先, 27列) 转成列优先 grid
def _norm(rows):
    out=[]
    for r in rows:
        r=r.replace(' ','#') if False else r
        r=r[:W]
        if len(r)<W: r=r+'#'*(W-len(r))
        out.append(r)
    return out

def from_art(rows):
    # rows: list of strings, 5 rows (top->bottom); auto-pad/trunc to 27 wide
    assert len(rows) == H, "need 5 rows"
    rows=_norm(rows)
    grid = []
    for x in range(W):
        col = ''.join(rows[y][x] for y in range(H))
        grid.append(col)
    return grid

